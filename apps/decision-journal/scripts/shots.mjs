// Screenshots at iPhone 15 size. Run `npx vite build && npx vite preview --port 4180` first.
import { chromium } from 'playwright'
const OUT = process.argv[2] || '.'
const URL = 'http://localhost:4180/'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
page.on('dialog', (d) => d.accept())
await page.addInitScript(() => document.addEventListener('DOMContentLoaded', () => { const st = document.createElement('style'); st.textContent = ':root{--st:47px!important;--sb:34px!important}'; document.head.appendChild(st) }))
const wait = (ms) => page.waitForTimeout(ms)
const shot = async (n) => { await page.screenshot({ path: `${OUT}/${n}.png` }); console.log('shot', n) }
const scr = (y, sel = '.screen') => page.locator(sel).first().evaluate((e, y) => e.scrollTo(0, y), y)
await page.goto(URL)
await wait(900); await shot('01-ob1')
await page.click('text=Get started'); await wait(700); await shot('02-ob2')
await page.click('text=Continue'); await wait(1600); await shot('03-ob3')
await page.click('text=Continue'); await wait(500)
await page.fill('.big-input', 'Bobby'); await shot('04-name')
await page.click('text=Explore with a sample journal'); await wait(1900); await shot('05-today-banner')
await wait(4500); await shot('06-today')
await scr(500); await wait(300); await shot('07-today-scroll'); await scr(0)
// Review flow
await page.locator('.due-card').first().locator('text=Look back').click(); await wait(700); await shot('08-review-lookback')
await page.click('text=How did it go?'); await wait(500); await shot('09-review-outcome')
await page.click('.face >> nth=3'); await wait(800); await shot('10-review-right')
await page.click('.opt-card >> nth=0'); await page.click('text=Continue'); await wait(500)
await page.fill('textarea.note', 'Best thing I did all year. He sleeps on my feet.'); await shot('11-review-note')
await page.click('text=Save check-in'); await wait(400); await shot('12-reveal-a'); await wait(1600); await shot('13-reveal')
await page.click('text=Done'); await wait(600)
// New decision
await page.click('[aria-label="New decision"]'); await wait(700); await shot('14-new-title')
await page.fill('.big-text', 'Take the Notion offer or keep building'); await page.click('.chip >> text=Work'); await shot('15-new-title-filled')
await page.click('text=Continue'); await wait(500); await shot('16-new-options')
await page.click('text=Continue'); await wait(500); await shot('17-new-gut')
await page.click('.gut-card >> nth=1'); await wait(900)
await page.fill('textarea.note', "The offer is $210k and I'm scared the app won't grow fast enough. But I've already put 8 months in and everyone says founders quit too early.")
await page.click('.chip >> text=Torn'); await shot('18-new-why')
await page.click('.ai-btn'); await wait(300); await shot('19-new-ai-thinking'); await wait(1600); await scr(400, '.flow-body'); await wait(200); await shot('20-new-ai')
await page.click('text=Continue'); await wait(500)
await page.click('.opt-card >> nth=0'); await page.fill('.line-input', 'Stable income, but I miss building my own thing'); await shot('21-new-choice')
await page.click('text=Seal it'); await wait(2200); await shot('22-sealed')
await page.click('.sealed >> text=Done'); await wait(700)
// Insights
await page.click('.tab >> text=Insights'); await wait(1600); await shot('23-insights')
await scr(560); await wait(500); await shot('24-insights-locked')
await page.click('text=Unlock with Plus'); await wait(700); await shot('25-paywall')
await page.click('text=Start 7-day free trial'); await wait(1700)
await scr(560); await wait(800); await shot('26-insights-plus')
await scr(1200); await wait(500); await shot('27-insights-plus2')
await scr(0); await page.click('.share-btn'); await wait(1500); await shot('28-share')
await page.mouse.click(200, 60); await wait(600)
// Journal + detail
await page.click('.tab >> text=Journal'); await wait(700); await shot('29-journal')
await page.click('text=Move to Austin'); await wait(800); await shot('30-detail')
await scr(600); await wait(300); await shot('31-detail-scroll')
await scr(2000); await wait(300); await shot('32-detail-bottom')
await page.click('[aria-label=Back]'); await wait(600)
await page.click('.tab >> text=You'); await wait(700); await shot('33-settings')
console.log('ERRORS', errs)
await browser.close()
