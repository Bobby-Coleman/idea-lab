import { chromium } from 'playwright'
const OUT = process.argv[2]
const URL = 'http://localhost:4173/'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await page.addInitScript(() => {
  document.addEventListener('DOMContentLoaded', () => {
    const st = document.createElement('style')
    st.textContent = ':root{--st:47px!important;--sb:34px!important}'
    document.head.appendChild(st)
  })
})
const wait = (ms) => page.waitForTimeout(ms)
const shot = async (n) => { await page.screenshot({ path: `${OUT}/${n}.png` }); console.log('shot', n) }
await page.goto(URL)
await wait(800); await shot('01-onb1')
await page.click('text=Continue'); await wait(900); await shot('02-onb2')
await page.click('text=Continue'); await wait(700); await shot('03-onb3')
await page.click('text=Start reading'); await wait(600); await shot('04-home')
await page.locator('.demo-card').first().click(); await wait(2600); await shot('05-analyzing')
await wait(3200); await wait(2800); await shot('06-result')
await page.locator('.screen').evaluate((e) => e.scrollTo(0, 620)); await wait(400); await shot('07-locked')
await page.click('text=Unlock the full read'); await wait(700); await shot('08-paywall')
await page.click('text=Start my free trial'); await wait(1800)
await page.locator('.screen').evaluate((e) => e.scrollTo(0, 640)); await wait(400); await shot('09-unlocked')
await page.locator('.screen').evaluate((e) => e.scrollTo(0, 1300)); await wait(300); await shot('10-unlocked2')
await page.locator('.screen').evaluate((e) => e.scrollTo(0, 0)); await wait(200)
await page.click('[aria-label=Share]'); await wait(1500); await shot('11-share')
await page.mouse.click(200, 60); await wait(400)
await page.click('[aria-label=Back]'); await wait(600)
await page.locator('.demo-card').nth(1).click(); await wait(8800); await shot('12-result-high')
await page.click('[aria-label=Back]'); await wait(600)
await page.locator('.demo-card').nth(2).click(); await wait(8800); await shot('13-result-mixed')
await page.locator('.screen').evaluate((e) => e.scrollTo(0, 1250)); await wait(300); await shot('14-horsemen')
await page.click('[aria-label=Back]'); await wait(600)
await page.click('[aria-label="New scan"]'); await wait(600); await shot('15-new')
await page.click('text=Paste text'); await page.click('text=Use example'); await wait(400); await shot('16-paste')
await page.click('text=Read it'); await wait(8800); await shot('17-paste-result')
await page.click('[aria-label=Back]'); await wait(500)
await page.click('.tab >> text=People'); await wait(500); await shot('18-people')
await page.locator('.row').first().click(); await wait(600); await shot('19-person')
await page.click('[aria-label=Back]'); await wait(300)
await page.click('.tab >> text=Home'); await wait(300)
await page.click('[aria-label=Settings]'); await wait(600); await shot('20-settings')
console.log('ERRORS', errs)
await browser.close()
